def ptn_to_path(ptn)
  ptn.gsub(/[a-z]/, '\0_')
end

# 1行の先頭文字から振り分け先のキーを決める。
def bucket_name_for(line)
  # 先頭がパターンにマッチするか正規表現で一発判定
  if (match = line.match(PATTERN_REGEXP))
    # match[1] には、実際にマッチしたパターンの文字列（例: "1a1" や "1"）が入る
    return ptn_to_path(match[1])
  end

  first_char = line[0]
  return "others" if first_char.nil?
  return ptn_to_path(first_char) if first_char.match?(/[0-9A-Za-z]/)

  "others"
end

# 1行の先頭文字から振り分け先のキーを決める。愚直
def bucket_name_for_old(line)
  firstchar = line[0]
  TABLE.each do |elem|
    return elem[:name] if line.start_with?(elem[:pattern])
  end

  return "others" if firstchar.nil?

  return firstchar if firstchar.match?(/[0-9A-Za-z]/)

  "others"
end

