# 1. パターンの長い順にソートして、1つの正規表現にまとめる（一度だけ実行）
# これにより、"1f1A" が "1" や "1f" より先にマッチするようになります
SORTED_PATTERN = TABLE_PATTERN.sort_by { |str| -str.length }.freeze
PATTERN_REGEXP = /\A(#{Regexp.union(SORTED_PATTERN).source})/

