def savelinebyline(inputpath, placeholder)
  begin
    # 入力を1行ずつ読み込み、対応するファイルへそのまま書き出す。
    File.foreach(inputpath, mode: "r:BOM|UTF-8") do |line|
      bucket = bucket_name_for(line)
      # handles[bucket] ||= File.open(outputpathfor(placeholder, bucket), "a:UTF-8")
      # handles[bucket].write(line)
      File.open(outputpathfor(placeholder, bucket), "a:UTF-8").write(line)
    end
  ensure
    # 途中で例外が出ても、開いたファイルはすべて閉じる。
    # handles.eachvalue(&:close)
  end
end

def savelinesonce(inputpath, placeholder)
  res = []

  data = File.open(inputpath, mode: "r:BOM|UTF-8").readlines()
  TABLE_PATTERN.each do |ptn|
    filtered, remain = data.partition do |l|
      l.start_with?(ptn)
    end

    data = remain

    unless filtered.empty? then
      File.open(outputpathfor(placeholder, ptn_to_path(ptn)), "a:UTF-8")
        .write(filtered.join())
    end
  end

  unless data.empty? then
    File.open(outputpathfor(placeholder, "others"), "a:UTF-8")
      .write(data.join())
  end
end

